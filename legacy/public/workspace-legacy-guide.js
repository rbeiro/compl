// Only the current guide's authorized DOCX is supplied by the document gateway.
// Read the two XML parts and a designated dish image; never follow external relationships.
const maxArchive=10*1024*1024, maxXML=3*1024*1024;
const word='http://schemas.openxmlformats.org/wordprocessingml/2006/main';
const draw='http://schemas.openxmlformats.org/drawingml/2006/main';
const drawing='http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing';
const relations='http://schemas.openxmlformats.org/officeDocument/2006/relationships';
const packageRelations='http://schemas.openxmlformats.org/package/2006/relationships';
const decoder=new TextDecoder('utf-8');
const nodes=(parent,ns,tag)=>Array.from(parent.getElementsByTagNameNS(ns,tag));
function zipEntries(bytes){
  const view=new DataView(bytes.buffer,bytes.byteOffset,bytes.byteLength);
  const u16=i=>view.getUint16(i,true),u32=i=>view.getUint32(i,true);
  let end=bytes.length-22;
  while(end>=Math.max(0,bytes.length-65557) && (u32(end)!==0x06054b50||end+22+u16(end+20)!==bytes.length))end--;
  if(end<0||u32(end)!==0x06054b50||u16(end+4)||u16(end+6)||u16(end+10)>768)throw Error('Invalid directory');
  const count=u16(end+10),entries=new Map();
  let at=u32(end+16);
  for(let n=0;n<count;n++){
    if(at+46>end||u32(at)!==0x02014b50)throw Error('Invalid directory entry');
    const len=u16(at+28),name=decoder.decode(bytes.subarray(at+46,at+46+len));
    const method=u16(at+10),compressed=u32(at+20),size=u32(at+24),local=u32(at+42);
    if(entries.has(name)||local+30>end||u32(local)!==0x04034b50)throw Error('Invalid file entry');
    const offset=local+30+u16(local+26)+u16(local+28);
    if(offset+compressed>end)throw Error('Invalid file length');
    entries.set(name,{method,compressed,size,offset});
    at+=46+len+u16(at+30)+u16(at+32);
  }
  return async(name,limit)=>{
    const item=entries.get(name);
    if(!item||item.size>limit||![0,8].includes(item.method))return null;
    const packed=bytes.subarray(item.offset,item.offset+item.compressed);
    if(!item.method)return packed.length===item.size?packed:null;
    const reader=new Blob([packed]).stream().pipeThrough(new DecompressionStream('deflate-raw')).getReader();
    const result=new Uint8Array(item.size);let n=0;
    try{
      while(true){
        const {done,value}=await reader.read();if(done)break;
        if(n+value.length>result.length){await reader.cancel();return null;}
        result.set(value,n);n+=value.length;
      }
    }finally{reader.releaseLock();}
    return n===result.length?result:null;
  };
}
function parseXML(bytes){
  if(!bytes)return null;
  const text=decoder.decode(bytes);
  if(/<!DOCTYPE|<!ENTITY/i.test(text))return null;
  const doc=new DOMParser().parseFromString(text,'application/xml');
  return doc.querySelector('parsererror')?null:doc;
}
function legacyData(doc){
  const data={pasos:[]};
  const content=el=>nodes(el,word,'t').map(x=>x.textContent).join('').trim();
  const text=nodes(doc,word,'p').map(content).filter(Boolean);
  for(const [key,label] of Object.entries({partida:'Partida',pase:'Tiempo de pase',racion:'Ración',vajilla:'Vajilla',codigo:'Código',version:'V'})){
    const expression=new RegExp('(?:^|·)\\s*'+label+'\\s*\\[([^\\]]{1,200})\\]','i');
    const value=text.map(t=>t.match(expression)).find(Boolean);
    if(value)data[key]=value[1].trim();
  }
  const sala=text.findIndex(t=>/^\d+\s+información para sala$/i.test(t));
  if(sala>=0){
    for(const [label,key] of [['ES','sala_es'],['Original','sala_es'],['EN','sala_en']]){
      const line=text.slice(sala+1,sala+5).find(t=>t.startsWith(label+' '));
      if(line)data[key]=line.slice(label.length).trim();
    }
  }
  for(const table of nodes(doc,word,'tbl')){
    const rows=Array.from(table.children).filter(n=>n.namespaceURI===word&&n.localName==='tr');
    const cells=row=>Array.from(row.children).filter(n=>n.namespaceURI===word&&n.localName==='tc').map(content);
    if(!rows.length)continue;
    const header=cells(rows[0]);
    const normalized=header.map(value=>value.trim().toLowerCase());
    const ingredient=normalized.indexOf('ingrediente'), quantity=normalized.indexOf('cantidad'), unit=normalized.indexOf('unidad');
    if(ingredient>=0 && quantity>=0 && unit>=0){
      data.ingredientes=rows.slice(1,41).map(row=>{
        const values=cells(row);
        return {nombre:values[ingredient],cantidad:values[quantity]||'',unidad:values[unit]||''};
      }).filter(item=>item.nombre);
    }
    if(header[0]?.trim().toLowerCase()!=='paso'||!/^acción\b/i.test(header[1]||''))continue;
    for(const row of rows.slice(1,101)){
      const [number,accion,control]=cells(row);
      if(/^\d{1,3}$/.test(number)&&accion)data.pasos.push({accion,control:control||''});
    }
  }
  // Versions generated by CompI put a bullet-delimited list in the final framed section.
  // Prefer explicit columns; infer a scalar only when the line ends in a known unit.
  if(!data.ingredientes?.length){
    const heading=text.lastIndexOf('Ingredientes');
    const framed=nodes(doc,word,'framePr').length>0;
    if(framed && heading>=0 && heading<text.length-1){
      const list=text.slice(heading+1).join(' ').split(/\s*•\s*/u);
      if(list.length<=40 && list.every(value=>value.length<=200)){
        data.ingredientes=list.map(value=>{
          const match=value.trim().match(/^(.+?)\s+(\d+(?:[.,]\d+)?)\s+(g|kg|gr|ml|cl|dl|l|ud|uds|unidades?)$/iu);
          return match ? {nombre:match[1],cantidad:match[2],unidad:match[3]} : {nombre:value.trim(),cantidad:'',unidad:''};
        }).filter(item=>item.nombre);
      }
    }
  }
  return data;
}
// Some Word exports name every photo "Picture" or "image3.png". In the guide
// template the dish drawing is followed by its "Referencia aprobada" caption.
function hasPlatingCaption(picture){
  let paragraph=picture.parentElement;
  while(paragraph && !(paragraph.namespaceURI===word && paragraph.localName==='p'))paragraph=paragraph.parentElement;
  if(!paragraph || nodes(paragraph,word,'drawing').length!==1)return false;
  for(let next=paragraph.nextElementSibling;next;next=next.nextElementSibling){
    if(next.namespaceURI!==word || next.localName!=='p' || nodes(next,word,'drawing').length)return false;
    const text=nodes(next,word,'t').map(node=>node.textContent).join('').trim();
    if(text)return /^referencia\s+aprobada\b/i.test(text);
  }
  return false;
}
async function platingImage(doc,read){
  const relationship=parseXML(await read('word/_rels/document.xml.rels',maxXML));
  if(!relationship)return null;
  for(const picture of nodes(doc,word,'drawing')){
    const properties=nodes(picture,drawing,'docPr')[0];
    const label=properties?.getAttribute('descr')||'',name=properties?.getAttribute('name')||'';
    if(/espacio para|\bpendientes?\b|placeholder|marcador|qr|logotipo/i.test(label+' '+name))continue;
    if(!/^(?:fotograf[ií]a de emplatado|emplatado de\b)/i.test(label)&&!/^Foto[_ -]/i.test(name)&&!hasPlatingCaption(picture))continue;
    const embed=nodes(picture,draw,'blip')[0]?.getAttributeNS(relations,'embed');
    const link=nodes(relationship,packageRelations,'Relationship').find(r=>r.getAttribute('Id')===embed);
    const target=link?.getAttribute('Target')||'';
    if(!link||link.getAttribute('TargetMode')==='External'||link.getAttribute('Type')!==relations+'/image'||
      !/^media\/[\p{L}\p{N}_. -]+\.(?:png|jpe?g)$/iu.test(target))continue;
    const bytes=await read('word/'+target,maxArchive);
    if(!bytes)continue;
    const png=[137,80,78,71,13,10,26,10].every((n,i)=>bytes[i]===n);
    const jpeg=bytes[0]===255&&bytes[1]===216&&bytes[2]===255;
    if(png||jpeg)return new Blob([bytes],{type:png?'image/png':'image/jpeg'});
  }
  return null;
}
export async function readLegacyGuide(blob){
  if(!blob||blob.size<22||blob.size>maxArchive)return null;
  try{
    const read=zipEntries(new Uint8Array(await blob.arrayBuffer()));
    const doc=parseXML(await read('word/document.xml',maxXML));
    if(!doc)return null;
    return {data:legacyData(doc),image:await platingImage(doc,read)};
  }catch{return null;}
}
