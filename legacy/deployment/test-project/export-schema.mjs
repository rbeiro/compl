// Reconstruye el ESQUEMA (sin datos) de un proyecto Supabase leyendo sus catalogos en modo solo lectura.
// Uso: node export-schema.mjs <ref-origen> <carpeta-salida>
// La salida contiene funciones con datos de negocio: guardarla FUERA de Git.
import {spawnSync} from 'node:child_process';
import {mkdirSync, writeFileSync, mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join, resolve} from 'node:path';

const [ref, outArg] = process.argv.slice(2);
if (!/^[a-z0-9]{20}$/.test(ref || '') || !outArg) { console.error('Uso: node export-schema.mjs <ref> <carpeta>'); process.exit(1); }
const out = resolve(outArg); mkdirSync(out, {recursive: true});
const tmp = mkdtempSync(join(tmpdir(), 'schema-'));
const SCHEMAS = "('public','compi_private')";

function query(sql) {
  const file = join(tmp, 'q.sql'); writeFileSync(file, sql);
  const r = spawnSync(`npx --yes supabase@latest db query --remote=${ref} --read-only --output-format json -f "${file}"`, {shell: true, encoding: 'utf8', maxBuffer: 1 << 28});
  const text = (r.stdout || '').includes('{') ? r.stdout : (r.stderr || '');
  const start = text.indexOf('{'); if (start < 0) throw new Error(text.slice(0, 400));
  const json = JSON.parse(text.slice(start));
  if (json.error) throw new Error(JSON.stringify(json.error).slice(0, 400));
  return json.rows;
}
const q = (s) => `"${String(s).replace(/"/g, '""')}"`;
const save = (name, parts) => { writeFileSync(join(out, name), parts.join('\n') + '\n'); console.log(name, parts.length, 'sentencias'); };

// 00 esquemas y extensiones
save('00_base.sql', [
  'create schema if not exists compi_private;',
  'create extension if not exists pgcrypto with schema extensions;',
  'create extension if not exists "uuid-ossp" with schema extensions;',
]);

// 01 tablas (sin restricciones)
const tables = query(`select c.oid::int oid, n.nspname s, c.relname t, c.relrowsecurity rls, c.relforcerowsecurity frc from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname in ${SCHEMAS} and c.relkind in ('r','p') order by 2,3`);
const cols = query(`select a.attrelid::int oid, a.attnum, a.attname, format_type(a.atttypid,a.atttypmod) ty, a.attnotnull nn, a.attidentity idt, a.attgenerated gen, pg_get_expr(d.adbin,d.adrelid) def from pg_attribute a left join pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum where a.attnum>0 and not a.attisdropped and a.attrelid in (select c.oid from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname in ${SCHEMAS} and c.relkind in ('r','p')) order by 1,2`);
const ddl = ['set check_function_bodies = off;'];
for (const t of tables) {
  const lines = cols.filter((c) => c.oid === t.oid).map((c) => {
    let l = `  ${q(c.attname)} ${c.ty}`;
    if (c.idt === 'a') l += ' generated always as identity'; else if (c.idt === 'd') l += ' generated by default as identity';
    else if (c.gen === 's') l += ` generated always as (${c.def}) stored`;
    else if (c.def != null) l += ` default ${c.def}`;
    if (c.nn) l += ' not null';
    return l;
  });
  ddl.push(`create table ${q(t.s)}.${q(t.t)} (\n${lines.join(',\n')}\n);`);
}
save('01_tablas.sql', ddl);

// 02 funciones
const funcs = query(`select p.oid::regprocedure::text sig, pg_get_functiondef(p.oid) d from pg_proc p where p.pronamespace::regnamespace::text in ${SCHEMAS} and p.prokind='f' order by 1`);
save('02_funciones.sql', ['set check_function_bodies = off;', ...funcs.map((f) => f.d.trimEnd() + ';')]);

// 03 vistas
const views = query(`select n.nspname s, c.relname v, pg_get_viewdef(c.oid,true) d from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname in ${SCHEMAS} and c.relkind='v' order by 1,2`);
save('03_vistas.sql', views.map((v) => `create or replace view ${q(v.s)}.${q(v.v)} as ${v.d.trimEnd().replace(/;$/, '')};`));

// 04 restricciones: primero pk/unique/check, despues claves foraneas
const cons = query(`select c.conrelid::regclass::text rel, c.conname, c.contype, pg_get_constraintdef(c.oid) d from pg_constraint c where c.conrelid in (select cl.oid from pg_class cl join pg_namespace n on n.oid=cl.relnamespace where n.nspname in ${SCHEMAS} and cl.relkind in ('r','p')) order by case c.contype when 'p' then 1 when 'u' then 2 when 'c' then 3 when 'x' then 4 else 5 end, 1, 2`);
save('04_restricciones.sql', cons.map((c) => `alter table ${c.rel} add constraint ${q(c.conname)} ${c.d};`));

// 05 indices que no respaldan restricciones
const idx = query(`select pg_get_indexdef(i.indexrelid) d from pg_index i join pg_class c on c.oid=i.indrelid join pg_namespace n on n.oid=c.relnamespace where n.nspname in ${SCHEMAS} and not exists (select 1 from pg_constraint k where k.conindid=i.indexrelid) order by 1`);
save('05_indices.sql', idx.map((i) => i.d + ';'));

// 06 disparadores (tablas propias y auth.users)
const trg = query(`select pg_get_triggerdef(t.oid) d from pg_trigger t where not t.tgisinternal and (t.tgrelid::regclass::text like 'public.%' or t.tgrelid::regclass::text like 'compi_private.%' or t.tgrelid::regclass::text = 'auth.users') order by 1`);
save('06_disparadores.sql', trg.map((t) => t.d + ';'));

// 07 seguridad por filas y politicas
const rls = [];
for (const t of tables) { if (t.rls) rls.push(`alter table ${q(t.s)}.${q(t.t)} enable row level security;`); if (t.frc) rls.push(`alter table ${q(t.s)}.${q(t.t)} force row level security;`); }
const pol = query(`select schemaname s, tablename t, policyname p, permissive, roles, cmd, qual, with_check from pg_policies where schemaname in ('public','compi_private') or (schemaname='storage' and tablename='objects') order by 1,2,3`);
for (const p of pol) {
  const list = Array.isArray(p.roles) ? p.roles : String(p.roles || '{}').replace(/[{}]/g, '').split(',').filter(Boolean);
  const roles = list.join(', ') || 'public';
  rls.push(`create policy ${q(p.p)} on ${q(p.s)}.${q(p.t)} as ${p.permissive.toLowerCase()} for ${p.cmd.toLowerCase()} to ${roles}` + (p.qual ? ` using (${p.qual})` : '') + (p.with_check ? ` with check (${p.with_check})` : '') + ';');
}
save('07_rls.sql', rls);

// 08 permisos (se parte de cero para las funciones y tablas, como en el origen)
const grants = [];
const roles = "('anon','authenticated','service_role')";
const tacl = query(`select n.nspname s, c.relname t, (a).grantee::regrole::text g, (a).privilege_type pt from pg_class c join pg_namespace n on n.oid=c.relnamespace, lateral aclexplode(c.relacl) a where n.nspname in ${SCHEMAS} and c.relkind in ('r','p','v') and (a).grantee::regrole::text in ${roles} order by 1,2,3,4`);
for (const t of tables) grants.push(`revoke all on table ${q(t.s)}.${q(t.t)} from anon, authenticated, service_role;`);
for (const v of views) grants.push(`revoke all on table ${q(v.s)}.${q(v.v)} from anon, authenticated, service_role;`);
for (const a of tacl) grants.push(`grant ${a.pt} on table ${q(a.s)}.${q(a.t)} to ${a.g};`);
const facl = query(`select p.oid::regprocedure::text sig, (select coalesce(string_agg(distinct (a).grantee::regrole::text,','),'') from aclexplode(p.proacl) a where (a).grantee::regrole::text in ${roles}) g, p.proacl is null nul from pg_proc p where p.pronamespace::regnamespace::text in ${SCHEMAS} and p.prokind='f' order by 1`);
for (const f of facl) if (!f.nul) { grants.push(`revoke all on function ${f.sig} from public, anon, authenticated, service_role;`); for (const g of f.g.split(',').filter(Boolean)) grants.push(`grant execute on function ${f.sig} to ${g};`); }
const sacl = query(`select n.nspname s, (a).grantee::regrole::text g, (a).privilege_type pt from pg_namespace n, lateral aclexplode(n.nspacl) a where n.nspname in ${SCHEMAS} and (a).grantee::regrole::text in ${roles}`);
for (const s of sacl) grants.push(`grant ${s.pt} on schema ${q(s.s)} to ${s.g};`);
save('08_permisos.sql', grants);

// 09 depositos de almacenamiento (solo definicion)
const bk = query(`select id, name, public, file_size_limit, allowed_mime_types from storage.buckets order by 1`);
const lit = (v) => v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
save('09_almacenamiento.sql', bk.map((b) => `insert into storage.buckets (id,name,public,file_size_limit,allowed_mime_types) values (${lit(b.id)},${lit(b.name)},${b.public},${b.file_size_limit ?? 'null'},${b.allowed_mime_types ? `'${JSON.stringify(b.allowed_mime_types).replace('[', '{').replace(']', '}').replace(/"/g, '"')}'` : 'null'}) on conflict (id) do nothing;`));
console.log('Listo. Salida en', out);
