// Reads the steps, service data and dish photo out of a plating guide that only
// exists as a Word file (guides uploaded before the generator existed).
// Port of legacy/public/workspace-legacy-guide.js, which did this in the
// browser with a hand-written ZIP reader; here jszip and @xmldom/xmldom do the
// parsing. The extraction rules are unchanged.
import { DOMParser, type Document, type Element } from "@xmldom/xmldom";
import JSZip from "jszip";

const maxArchive = 10 * 1024 * 1024;
const maxXML = 3 * 1024 * 1024;
const word = "http://schemas.openxmlformats.org/wordprocessingml/2006/main";
const draw = "http://schemas.openxmlformats.org/drawingml/2006/main";
const drawing = "http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing";
const relations = "http://schemas.openxmlformats.org/officeDocument/2006/relationships";
const packageRelations = "http://schemas.openxmlformats.org/package/2006/relationships";

type Node = Element | Document;
const nodes = (parent: Node, ns: string, tag: string) => Array.from(parent.getElementsByTagNameNS(ns, tag)) as Element[];
const children = (el: Element, tag: string) =>
  Array.from(el.childNodes).filter((n): n is Element => (n as Element).namespaceURI === word && (n as Element).localName === tag);

export type LegacyGuideData = {
  pasos: { accion: string; control: string }[];
  ingredientes?: { nombre: string; cantidad: string; unidad: string }[];
  [key: string]: unknown;
};
export type LegacyGuide = { data: LegacyGuideData; image: { bytes: Uint8Array; type: "image/png" | "image/jpeg" } | null };

function parseXML(text: string | null): Document | null {
  if (!text || /<!DOCTYPE|<!ENTITY/i.test(text)) return null;
  try {
    let failed = false;
    const doc = new DOMParser({
      onError: (level) => {
        if (level !== "warning") failed = true;
      },
    }).parseFromString(text, "application/xml");
    return failed ? null : doc;
  } catch {
    return null;
  }
}

async function readEntry(zip: JSZip, name: string, limit: number, type: "string"): Promise<string | null>;
async function readEntry(zip: JSZip, name: string, limit: number, type: "uint8array"): Promise<Uint8Array | null>;
async function readEntry(zip: JSZip, name: string, limit: number, type: "string" | "uint8array") {
  const file = zip.file(name);
  if (!file) return null;
  const size = (file as unknown as { _data?: { uncompressedSize?: number } })._data?.uncompressedSize;
  if (typeof size === "number" && size > limit) return null;
  const value = await file.async(type);
  const length = typeof value === "string" ? value.length : value.byteLength;
  return length > limit ? null : value;
}

function legacyData(doc: Document): LegacyGuideData {
  const data: LegacyGuideData = { pasos: [] };
  const content = (el: Element) => nodes(el, word, "t").map((x) => x.textContent ?? "").join("").trim();
  const text = nodes(doc, word, "p").map(content).filter(Boolean);
  const labels = { partida: "Partida", pase: "Tiempo de pase", racion: "Ración", vajilla: "Vajilla", codigo: "Código", version: "V" };
  for (const [key, label] of Object.entries(labels)) {
    const expression = new RegExp("(?:^|·)\\s*" + label + "\\s*\\[([^\\]]{1,200})\\]", "i");
    const value = text.map((t) => t.match(expression)).find(Boolean);
    if (value) data[key] = value[1]!.trim();
  }
  const sala = text.findIndex((t) => /^\d+\s+información para sala$/i.test(t));
  if (sala >= 0) {
    for (const [label, key] of [["ES", "sala_es"], ["Original", "sala_es"], ["EN", "sala_en"]] as const) {
      const line = text.slice(sala + 1, sala + 5).find((t) => t.startsWith(label + " "));
      if (line) data[key] = line.slice(label.length).trim();
    }
  }
  for (const table of nodes(doc, word, "tbl")) {
    const rows = children(table, "tr");
    const cells = (row: Element) => children(row, "tc").map(content);
    if (!rows.length) continue;
    const header = cells(rows[0]!);
    const normalized = header.map((value) => value.trim().toLowerCase());
    const ingredient = normalized.indexOf("ingrediente"), quantity = normalized.indexOf("cantidad"), unit = normalized.indexOf("unidad");
    if (ingredient >= 0 && quantity >= 0 && unit >= 0) {
      data.ingredientes = rows
        .slice(1, 41)
        .map((row) => {
          const values = cells(row);
          return { nombre: values[ingredient] ?? "", cantidad: values[quantity] || "", unidad: values[unit] || "" };
        })
        .filter((item) => item.nombre);
    }
    if (header[0]?.trim().toLowerCase() !== "paso" || !/^acción\b/i.test(header[1] || "")) continue;
    for (const row of rows.slice(1, 101)) {
      const [number, accion, control] = cells(row);
      if (/^\d{1,3}$/.test(number ?? "") && accion) data.pasos.push({ accion, control: control || "" });
    }
  }
  // Versions generated by CompI put a bullet-delimited list in the final framed section.
  if (!data.ingredientes?.length) {
    const heading = text.lastIndexOf("Ingredientes");
    const framed = nodes(doc, word, "framePr").length > 0;
    if (framed && heading >= 0 && heading < text.length - 1) {
      const list = text.slice(heading + 1).join(" ").split(/\s*•\s*/u);
      if (list.length <= 40 && list.every((value) => value.length <= 200)) {
        data.ingredientes = list
          .map((value) => {
            const match = value.trim().match(/^(.+?)\s+(\d+(?:[.,]\d+)?)\s+(g|kg|gr|ml|cl|dl|l|ud|uds|unidades?)$/iu);
            return match ? { nombre: match[1]!, cantidad: match[2]!, unidad: match[3]! } : { nombre: value.trim(), cantidad: "", unidad: "" };
          })
          .filter((item) => item.nombre);
      }
    }
  }
  return data;
}

const isWordElement = (n: unknown, tag: string): n is Element =>
  !!n && (n as Element).namespaceURI === word && (n as Element).localName === tag;

function nextElement(el: Element): Element | null {
  let next = el.nextSibling;
  while (next && next.nodeType !== 1) next = next.nextSibling;
  return next as Element | null;
}

// In the guide template the dish drawing is followed by its "Referencia aprobada" caption.
function hasPlatingCaption(picture: Element) {
  let paragraph: Element | null = picture.parentNode as Element | null;
  while (paragraph && !isWordElement(paragraph, "p")) paragraph = (paragraph as Element).parentNode as Element | null;
  if (!paragraph || nodes(paragraph, word, "drawing").length !== 1) return false;
  for (let next = nextElement(paragraph); next; next = nextElement(next)) {
    if (!isWordElement(next, "p") || nodes(next, word, "drawing").length) return false;
    const text = nodes(next, word, "t").map((node) => node.textContent ?? "").join("").trim();
    if (text) return /^referencia\s+aprobada\b/i.test(text);
  }
  return false;
}

async function platingImage(doc: Document, zip: JSZip): Promise<LegacyGuide["image"]> {
  const relationship = parseXML(await readEntry(zip, "word/_rels/document.xml.rels", maxXML, "string"));
  if (!relationship) return null;
  for (const picture of nodes(doc, word, "drawing")) {
    const properties = nodes(picture, drawing, "docPr")[0];
    const label = properties?.getAttribute("descr") || "", name = properties?.getAttribute("name") || "";
    if (/espacio para|\bpendientes?\b|placeholder|marcador|qr|logotipo/i.test(label + " " + name)) continue;
    if (!/^(?:fotograf[ií]a de emplatado|emplatado de\b)/i.test(label) && !/^Foto[_ -]/i.test(name) && !hasPlatingCaption(picture)) continue;
    const embed = nodes(picture, draw, "blip")[0]?.getAttributeNS(relations, "embed");
    const link = nodes(relationship, packageRelations, "Relationship").find((r) => r.getAttribute("Id") === embed);
    const target = link?.getAttribute("Target") || "";
    if (
      !link ||
      link.getAttribute("TargetMode") === "External" ||
      link.getAttribute("Type") !== relations + "/image" ||
      !/^media\/[\p{L}\p{N}_. -]+\.(?:png|jpe?g)$/iu.test(target)
    ) continue;
    const bytes = await readEntry(zip, "word/" + target, maxArchive, "uint8array");
    if (!bytes) continue;
    const png = [137, 80, 78, 71, 13, 10, 26, 10].every((n, i) => bytes[i] === n);
    const jpeg = bytes[0] === 255 && bytes[1] === 216 && bytes[2] === 255;
    if (png || jpeg) return { bytes, type: png ? "image/png" : "image/jpeg" };
  }
  return null;
}

/** Null when the file is not a readable Word guide. */
export async function readLegacyGuide(bytes: Uint8Array): Promise<LegacyGuide | null> {
  if (bytes.byteLength < 22 || bytes.byteLength > maxArchive) return null;
  try {
    const zip = await JSZip.loadAsync(bytes);
    if (Object.keys(zip.files).length > 768) return null;
    const doc = parseXML(await readEntry(zip, "word/document.xml", maxXML, "string"));
    if (!doc) return null;
    return { data: legacyData(doc), image: await platingImage(doc, zip) };
  } catch {
    return null;
  }
}
